// Installs docs/spec/AI_FITNESS_COACH_SYSTEM_PROMPT_V2.md as the single backend coach instruction.
// Keeps the runtime sections (identity → output contract); drops the implementer notes and
// reference links, which are not model instructions. The product name follows the app rename
// (AapnaFit → TrainLuma, decision D13). Writes supabase/functions/_shared/coachPrompt.ts with a SHA-256.
// Usage: node scripts/build-coach-prompt.mjs [--check]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'docs/spec/AI_FITNESS_COACH_SYSTEM_PROMPT_V2.md';
const OUT = 'supabase/functions/_shared/coachPrompt.ts';

export function runtimePrompt(md) {
  const start = md.indexOf('## Identity and scope');
  const end = md.indexOf('## Backend implementation notes');
  if (start < 0 || end < 0) throw new Error('prompt sections not found');
  return md.slice(start, end).trim().replaceAll('AapnaFit Coach', 'TrainLuma Coach').replaceAll('AapnaFit', 'TrainLuma') + '\n';
}

const text = runtimePrompt(readFileSync(SRC, 'utf8'));
const sha = createHash('sha256').update(text).digest('hex');
const ts = `// GENERATED by scripts/build-coach-prompt.mjs from ${SRC}. Do not edit by hand.
// The single runtime system instruction for every coach operation (schema 2.0).

export const COACH_PROMPT_SOURCE = 'AI_FITNESS_COACH_SYSTEM_PROMPT_V2.md (2.0, 2026-10-09)';
export const COACH_PROMPT_SHA256 = '${sha}';
/** Auditable without exposing context: source version + content hash prefix. */
export const PROMPT_VERSION = 'coach-2.0+${sha.slice(0, 12)}';

export const COACH_SYSTEM_PROMPT = ${JSON.stringify(text)};
`;
if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== ts) { console.error(`${OUT} is out of date; run node scripts/build-coach-prompt.mjs`); process.exit(1); }
  console.log('coach prompt up to date', sha.slice(0, 12));
} else {
  writeFileSync(OUT, ts);
  console.log('wrote', OUT, sha.slice(0, 12));
}
